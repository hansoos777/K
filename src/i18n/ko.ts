/** 받침이 있으면 '을', 없으면 '를' (괄호 설명은 건너뜀) */
const obj = (w: string) => {
  const c = w.replace(/\s*\([^)]*\)\s*$/, '').trim().slice(-1).charCodeAt(0)
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 ? '을' : '를'
}

